// Core domain types shared by the UI, services, demo store and Supabase store.
// Calendar dates are "yyyy-MM-dd" strings in the project's local timezone.
// Instants (check-in/out) are ISO-8601 UTC strings.

export type Role = "admin" | "operator";

export interface Profile {
  id: string;
  fullName: string;
  email: string;
  role: Role;
  isActive: boolean;
  createdAt: string;
}

export type ContractorIdentityStatus = "confirmed" | "needs_review";

export interface Contractor {
  id: string;
  name: string;
  /** null when not recorded (e.g. imported from a wage sheet that has no address). */
  location: string | null;
  /** Name as written on the contractor's own documents, e.g. a wage-sheet heading. */
  legalName: string | null;
  /** "needs_review" until an admin confirms who this contractor is (e.g. sheet name and heading disagree). */
  identityStatus: ContractorIdentityStatus;
  identityNote: string | null;
  photoPath: string | null;
  /** Resolved, displayable URL (signed URL or data URL). Never persisted. */
  photoUrl: string | null;
  isActive: boolean;
  createdAt: string;
  updatedAt: string;
}

/** A project site. Its attendance rules live in attendance policies (see domain/policy.ts). */
export interface Project {
  id: string;
  name: string;
  location: string;
  isActive: boolean;
  /** IANA timezone, e.g. "Asia/Kolkata". Locked once the site has attendance. */
  timezone: string;
  createdAt: string;
  updatedAt: string;
}

export interface ContractorProjectAssignment {
  id: string;
  contractorId: string;
  projectId: string;
  startDate: string;
  endDate: string | null;
}

export interface Worker {
  id: string;
  /** Human-friendly immutable code, e.g. W-00012. Generated by the system. */
  code: string;
  /**
   * The contractor's own employee ID, exactly as on their records (spaces and
   * leading zeros kept, e.g. "0F 8003"). The key for matching imports and registers.
   */
  employeeCode: string | null;
  fullName: string;
  contractorId: string;
  department: string | null;
  designation: string | null;
  isActive: boolean;
  phone: string | null;
  notes: string | null;
  /** Where the record came from, e.g. "Contractors Details.xlsx · Sumit · row 6". */
  source: string | null;
  createdAt: string;
  updatedAt: string;
}

/** How a worker's rate amount is meant: per month, per day, per hour, or not yet confirmed. */
export type RateBasis = "monthly" | "daily" | "hourly" | "unconfirmed";

/**
 * A worker's pay terms from a date: the rate amount exactly as recorded, its basis,
 * and (for contractors whose commission applies to selected workers) eligibility.
 * Append-only versions, so earlier months can always be recalculated as they were.
 */
export interface WorkerPayTerms {
  id: string;
  workerId: string;
  version: number;
  effectiveFrom: string;
  /** The amount as recorded, independent of its basis. null = not recorded. */
  rateAmount: number | null;
  rateBasis: RateBasis;
  /** null = not selected. Only used when the contractor's commission applies to selected workers. */
  commissionEligible: boolean | null;
  source: string | null;
  notes: string | null;
  createdAt: string;
  createdBy: string | null;
}

export type ImportKind = "worker_master" | "worker_contacts" | "historical_attendance";

/** A record of an applied import: which file, what it did, and who ran it. */
export interface ImportBatch {
  id: string;
  kind: ImportKind;
  fileName: string;
  /** SHA-256 of the uploaded file, so the same file is recognised when imported again. */
  fileHash: string;
  summary: Record<string, unknown>;
  createdAt: string;
  createdBy: string | null;
}

/** Effective-dated worker deployment. endDate is inclusive; null = open-ended. */
export interface WorkerAssignment {
  id: string;
  workerId: string;
  projectId: string;
  contractorId: string;
  startDate: string;
  endDate: string | null;
  createdAt: string;
}

export interface OperatorAccess {
  id: string;
  operatorId: string;
  projectId: string;
  grantedAt: string;
  revokedAt: string | null;
}

export type AttendanceStatus = "pending" | "present" | "absent";
export type ChangeMethod = "individual" | "bulk";
/** How an IN time was recorded: typed/picked by the operator, or the site's suggested time accepted as-is. */
export type CheckInSource = "entered" | "suggested";
/** Day or night shift. A night shift's OUT is normally on the next calendar day; workDate is the date the shift starts. */
export type Shift = "day" | "night";

export interface AttendanceRecord {
  id: string;
  workerId: string;
  projectId: string;
  /** Contractor the worker was supplied by on this date (snapshot). */
  contractorId: string;
  workDate: string;
  status: AttendanceStatus;
  checkInAt: string | null;
  checkOutAt: string | null;
  /** null for absent/pending, and for present records saved before this was tracked. */
  checkInSource: CheckInSource | null;
  shift: Shift;
  method: ChangeMethod;
  version: number;
  createdAt: string;
  updatedAt: string;
  createdBy: string | null;
  updatedBy: string | null;
}

export type RateType = "per_day" | "per_hour";
/** "contractor": one rate in the rule. "worker": each worker's own rate and basis (worker pay terms). */
export type RateSource = "contractor" | "worker";
/** Overtime paid at a fixed rupee rate per hour, or at a multiple of the worker's hourly equivalent. */
export type OvertimeRateMode = "per_hour" | "multiplier";
/** How overtime minutes are rounded before they are paid. */
export type OvertimeRounding = "exact" | "floor_15" | "floor_30" | "floor_60" | "nearest_15" | "nearest_30";
/** How a day-rated worker is paid for a completed day shorter than the standard hours. */
export type ShortDayPolicy = "pro_rata" | "half_day" | "full_day";
/** What commission is a percentage of: base wages only, or base wages plus overtime. */
export type CommissionBase = "base_wages" | "gross_wages";
/** Whether commission is paid to the contractor on top of wages, or taken out of the workers' wages. */
export type CommissionTreatment = "added_to_contractor_payable" | "deducted_from_wages";

/**
 * Immutable, versioned payment rule. A new version is created for every change.
 * A null setting the calculation needs means "not configured": affected amounts
 * show "Needs configuration" instead of a guessed figure.
 */
export interface PaymentRule {
  id: string;
  contractorId: string;
  version: number;
  effectiveFrom: string;
  rateSource: RateSource;
  /** Used when rateSource is "contractor". */
  rateType: RateType;
  dayRate: number | null;
  hourRate: number | null;
  /** Standard working hours for a full day. */
  fullDayHours: number | null;
  /** With shortDayPolicy "half_day": a shorter day of at least this many hours is half a day. */
  halfDayHours: number | null;
  /** Short completed days (day rates only). */
  shortDayPolicy: ShortDayPolicy | null;
  /** Workers paid a monthly salary: day rate = salary ÷ this many days. */
  monthlyDivisorDays: number | null;
  overtimeEnabled: boolean;
  /** Overtime starts after this many worked hours on a day shift... */
  overtimeAfterHours: number | null;
  /** ...and after this many on a night shift (null = same as day). */
  overtimeAfterNightHours: number | null;
  overtimeRateMode: OvertimeRateMode | null;
  /** Rupees per overtime hour (mode "per_hour"). */
  overtimeHourRate: number | null;
  /** Times the hourly equivalent (mode "multiplier"). */
  overtimeMultiplier: number | null;
  overtimeRounding: OvertimeRounding | null;
  /** Overtime shorter than this is not paid. */
  overtimeMinMinutes: number;
  unpaidBreakMinutes: number;
  commissionEnabled: boolean;
  commissionPercent: number | null;
  /** "selected": only workers marked eligible in their pay terms. */
  commissionScope: "all" | "selected" | null;
  commissionBase: CommissionBase | null;
  commissionTreatment: CommissionTreatment | null;
  notes: string | null;
  createdAt: string;
  createdBy: string | null;
}

export interface AttendanceSnapshot {
  status: AttendanceStatus;
  checkInAt: string | null;
  checkOutAt: string | null;
  /** Absent from audit entries written before this was tracked. */
  checkInSource?: CheckInSource | null;
  /** Absent from audit entries written before shifts were tracked (they were day shifts). */
  shift?: Shift;
}

export interface AuditLog {
  id: string;
  attendanceId: string;
  workerId: string;
  projectId: string;
  contractorId: string;
  workDate: string;
  action: "create" | "update";
  method: ChangeMethod;
  changedBy: string | null;
  changedByRole: Role | null;
  changedAt: string;
  oldValues: AttendanceSnapshot | null;
  newValues: AttendanceSnapshot;
}

export interface Actor {
  id: string;
  role: Role;
  fullName: string;
  email: string;
}
